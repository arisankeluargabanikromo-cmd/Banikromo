--  Hasil audit modul arisan setelah perubahan ke "putaran" (v3.16.0):
--   1) reopen_draw: pemenang yang dananya SUDAH DICAIRKAN bisa dibatalkan -> uang keluar ke orang yang "tidak hadir",
