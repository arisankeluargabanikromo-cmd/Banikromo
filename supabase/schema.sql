 perform pg_advisory_xact_lock(hashtext('fh_reset'));
 perform set_config('fh.skip_recalc','1',true);

 if p_scope in('arisan','anggota','semua') then
  select count(*) into c from draws; n:=n||jsonb_build_object('draws',c);
  delete from draws where id is not null;
  update settings set v='1' where k='cycle';
  select count(*) into c from arisan_rounds; n:=n||jsonb_build_object('arisan_rounds',c);
  delete from arisan_rounds where id is not null;       -- putaran & riwayat pengocokan satu paket; nomor putaran mulai dari 1 lagi
  insert into settings(k,v) values('disburse_from_seq','1') on conflict(k) do update set v='1';
