create function public.get_payments(p_period text default null) returns jsonb language sql stable security definer set search_path=public as $$
 select jsonb_build_object('period',x.p,'iuran',cfg('iuran')::int,'rows',coalesce((select jsonb_agg(jsonb_build_object('member_id',m.id,'name',m.name,'relation',m.relation,'pid',py.id,'amount',py.amount,'paid_at',py.paid_at) order by m.name) from members m left join payments py on py.member_id=m.id and py.period=x.p where m.active=1),'[]'::jsonb))
