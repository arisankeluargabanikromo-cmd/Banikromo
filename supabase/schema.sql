-- ====== patch-015-periode-manual.sql ======
-- ============================================================
-- PATCH 015 — Periode arisan ditentukan MANUAL (FamilyHub v3.14)
--  Sebelumnya "periode arisan" otomatis = bulan kalender (cur_period). Akibatnya pada tanggal 1 setiap bulan, periode
--  berganti sendiri walau arisan bulan lalu belum diundi / dicairkan. Kini admin yang menentukan periode aktif:
--   1) Tabel arisan_periods: satu periode AKTIF (dijamin indeks unik) + riwayat periode 'selesai', lengkap dengan
--      siapa yang membuka/menutup, kapan, dan catatan penutupan.
--   2) cur_period() = periode aktif tersebut (bila belum ada, jatuh ke bulan kalender). Seluruh kocokan, dashboard,
--      penagihan, tunggakan, dan portal anggota otomatis mengikuti periode aktif.
--   3) set_active_period(periode, catatan, paksa): menutup periode aktif lalu mengaktifkan periode pilihan admin.
--      Penjaga: format YYYY-MM, tidak lebih dari 12 bulan ke depan, tidak bisa saat ada pemenang "menunggu",
--      periode tanpa pemenang sah hanya bisa ditutup dengan alasan tertulis. Periode lama boleh dibuka kembali.
--   4) period_state(): daftar periode + ringkasan (pemenang, dana terkumpul/dicairkan) + selisih terhadap kalender.
--   5) Jejak audit (trg_audit), log aktivitas, ikut Backup/Restore & Reset. run_draw menolak bila tak ada periode aktif.
-- Instalasi lama: periode aktif awal = bulan kalender saat patch dijalankan (tak ada perubahan tampilan hari ini);
-- periode dari riwayat kocokan dicatat sebagai 'selesai'. Aman dijalankan berulang. Prasyarat: patch-011.
-- ============================================================

-- ---------- 1. Tabel periode ----------
create table if not exists public.arisan_periods(
  id bigint generated by default as identity primary key,
  period text not null unique check(period ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  status text not null default 'aktif' check(status in('aktif','selesai')),
  opened_at timestamptz not null default now(),
  opened_by text,
  closed_at timestamptz,
  closed_by text,
  close_note text,
  check((status='aktif') = (closed_at is null))
);
create unique index if not exists arisan_periods_satu_aktif on public.arisan_periods((true)) where status='aktif';   -- paling banyak SATU periode aktif
alter table public.arisan_periods enable row level security;
drop policy if exists "baca" on public.arisan_periods;
create policy "baca" on public.arisan_periods for select to authenticated using (public.is_approved());
revoke all on public.arisan_periods from anon, authenticated;
grant select on public.arisan_periods to authenticated;      -- tulis HANYA lewat set_active_period()

-- ---------- 2. Periode aktif ----------
create or replace function public.calendar_period() returns text language sql stable set search_path=public as $$
 select to_char(now() at time zone 'Asia/Jakarta','YYYY-MM') $$;

create or replace function public.cur_period() returns text language sql stable set search_path=public as $$
 select coalesce((select period from arisan_periods where status='aktif'),to_char(now() at time zone 'Asia/Jakarta','YYYY-MM')) $$;

-- Pembantu internal: pastikan ada tepat satu periode aktif & setiap periode di riwayat kocokan punya baris.
create or replace function public._ensure_periods() returns void language plpgsql security definer set search_path=public as $$
declare cal text:=calendar_period();
begin
 if not exists(select 1 from arisan_periods where status='aktif') then
  if exists(select 1 from arisan_periods where period=cal) then
   update arisan_periods set status='aktif',closed_at=null,closed_by=null,close_note=null where period=cal;
  else
   insert into arisan_periods(period,status,opened_by) values(cal,'aktif','sistem');
  end if;
 end if;
 insert into arisan_periods(period,status,opened_by,closed_at,closed_by,close_note)
  select d.period,'selesai','sistem',max(d.at),'sistem','Dibentuk otomatis dari riwayat pengocokan'
  from draws d where d.period ~ '^\d{4}-(0[1-9]|1[0-2])$' and not exists(select 1 from arisan_periods p where p.period=d.period) group by d.period;
end $$;
select public._ensure_periods();      -- instalasi lama: periode aktif awal = bulan kalender; (tanpa audit: pemicu dipasang sesudah ini)

drop trigger if exists audit_period_ins on public.arisan_periods;
drop trigger if exists audit_period_upd on public.arisan_periods;
create trigger audit_period_ins after insert on public.arisan_periods for each row execute function public.trg_audit();
create trigger audit_period_upd after update on public.arisan_periods for each row execute function public.trg_audit();

-- ---------- 3. Ringkasan untuk layar "Kelola periode" ----------
create or replace function public.period_state() returns jsonb language plpgsql stable security definer set search_path=public as $$
declare a text:=cur_period(); cal text:=calendar_period(); mx text;
begin
 perform need_approved();
 select max(period) into mx from arisan_periods;
 return jsonb_build_object('active',a,'calendar',cal,
  'behind',(substr(cal,1,4)::int*12+substr(cal,6,2)::int)-(substr(a,1,4)::int*12+substr(a,6,2)::int),     -- >0: kalender sudah melewati periode aktif
  'suggest',to_char(to_date(coalesce(mx,a)||'-01','YYYY-MM-DD')+interval '1 month','YYYY-MM'),
  'rows',coalesce((select jsonb_agg(to_jsonb(x) order by x.period desc) from (
    select p.period,p.status,p.opened_at,p.opened_by,p.closed_at,p.closed_by,p.close_note,
      (select count(*) from draws d where d.period=p.period)::int attempts,
      (select d.winner_name from draws d where d.period=p.period and d.status='sah') winner,
      (select count(*) from draws d where d.period=p.period and d.status='menunggu')::int pending,
      coalesce((select sum(y.amount) from payments y join fee_types f on f.id=y.fee_type_id where y.period=p.period and f.fund='arisan'),0)::bigint collected,
      coalesce((select sum(t.amount) from transactions t where t.category='Pencairan Arisan' and t.period=p.period),0)::bigint disbursed
    from arisan_periods p) x),'[]'::jsonb));
end $$;

-- ---------- 4. Ganti periode aktif (hanya admin) ----------
create or replace function public.set_active_period(p_period text,p_note text default null,p_force boolean default false) returns jsonb language plpgsql security definer set search_path=public as $$
declare cur arisan_periods; tgt arisan_periods; who text; lim text; reopened boolean:=false;
begin
 perform need_admin();
 perform pg_advisory_xact_lock(hashtext('fh_run_draw'));      -- sejajar dengan run_draw: tidak boleh bersamaan dengan pengocokan
 p_period:=trim(p_period);
 if p_period is null or p_period !~ '^\d{4}-(0[1-9]|1[0-2])$' then raise exception 'Periode tidak valid (format YYYY-MM)'; end if;
 if p_period<'2000-01' then raise exception 'Periode terlalu lampau'; end if;
 lim:=to_char((now() at time zone 'Asia/Jakarta')+interval '12 months','YYYY-MM');
 if p_period>lim then raise exception 'Periode terlalu jauh ke depan (maksimal 12 bulan dari sekarang)'; end if;
 select name into who from profiles where id=auth.uid();
 select * into cur from arisan_periods where status='aktif' for update;
 if found then
  if cur.period=p_period then raise exception 'Periode % sudah aktif',p_period; end if;
  if exists(select 1 from draws where period=cur.period and status='menunggu') then
   raise exception 'Periode % masih punya pemenang yang menunggu konfirmasi kehadiran. Selesaikan dulu di pengocokan.',cur.period; end if;
  if not exists(select 1 from draws where period=cur.period and status='sah') then
   if not coalesce(p_force,false) then raise exception 'Periode % belum punya pemenang yang disahkan. Sahkan pemenang dulu, atau tutup tanpa pemenang dengan alasan tertulis.',cur.period; end if;
   if coalesce(trim(p_note),'')='' then raise exception 'Alasan wajib diisi bila periode ditutup tanpa pemenang'; end if;
  end if;
  update arisan_periods set status='selesai',closed_at=now(),closed_by=coalesce(who,'admin'),close_note=nullif(trim(p_note),'') where id=cur.id;
 end if;
 select * into tgt from arisan_periods where period=p_period for update;
 if found then
  update arisan_periods set status='aktif',closed_at=null,closed_by=null,close_note=null where id=tgt.id;   -- buka kembali (jejak lama tersimpan di audit_log)
  reopened:=true;
 else
  insert into arisan_periods(period,status,opened_by) values(p_period,'aktif',coalesce(who,'admin'));
 end if;
 perform log_act('📅','Periode arisan '||p_period||case when reopened then ' dibuka kembali' else ' dibuka' end,
  case when cur.period is not null then 'periode '||cur.period||' ditutup' else 'tanpa periode sebelumnya' end);
 return jsonb_build_object('active',p_period,'closed',cur.period,'reopened',reopened);
end $$;

-- ---------- 7. Fungsi yang disesuaikan (disalin dari definisi terkini + perubahan minimal) ----------
-- run_draw: menolak mengocok bila tidak ada periode aktif.
create or replace function public.run_draw() returns jsonb language plpgsql security definer set search_path=public as $$
declare p text:=cur_period(); w record; ids text; n int; proof text; at_ timestamptz:=now(); att int; did bigint;
begin
 perform need_admin();
 if not exists(select 1 from arisan_periods where status='aktif') then raise exception 'Belum ada periode arisan aktif. Buka periode terlebih dahulu (Arisan → Kelola periode).'; end if;
 perform pg_advisory_xact_lock(hashtext('fh_run_draw'));   -- cegah dua pengocokan bersamaan
 if exists(select 1 from draws where period=p and status='sah') then raise exception 'Pengundian periode % sudah disahkan',p; end if;
 if exists(select 1 from draws where period=p and status='menunggu') then raise exception 'Masih ada pemenang yang menunggu konfirmasi kehadiran'; end if;
 select count(*),(to_jsonb(array_agg(e.id order by e.id)))::text into n,ids from eligible_members(p) e;
 if n=0 then raise exception 'Tidak ada peserta eligible (belum bayar, sudah menang di siklus ini, atau semua dilewati karena tidak hadir)'; end if;
 select e.id,e.name into w from eligible_members(p) e order by gen_random_uuid() limit 1;  -- acak kriptografis (UUID v4)
 select count(*)+1 into att from draws where period=p;
 proof:=encode(sha256(convert_to(p||'|'||at_::text||'|'||ids||'|'||w.id||'|'||gen_random_uuid()::text,'UTF8')),'hex');
 insert into draws(cycle,period,at,participants,winner_id,winner_name,proof,status,attempt)
  values(cfg('cycle')::int,p,at_,ids,w.id,w.name,proof,'menunggu',att) returning id into did;
 return jsonb_build_object('id',did,'attempt',att,'pool',n,'winner',jsonb_build_object('id',w.id,'name',w.name),'at',at_,'proof',proof);
end $$;

-- _restore_rows: daftar tabel yang boleh dipulihkan kini mencakup arisan_periods.
create or replace function public._restore_rows(p_table text,p_rows jsonb) returns void language plpgsql security definer set search_path=public as $$
declare cols text;
begin
 if p_table is null or p_table not in('arisan_periods','fee_types','members','payments','transactions','events','announcements','albums','photos','draws','activity') then raise exception 'Tabel tidak dikenal: %',p_table; end if;
 if p_rows is null or jsonb_typeof(p_rows)<>'array' or jsonb_array_length(p_rows)=0 then return; end if;
 select string_agg(format('%I',c.column_name),',' order by c.ordinal_position) into cols
  from information_schema.columns c
  where c.table_schema='public' and c.table_name=p_table
    and c.column_name in(select distinct k from jsonb_array_elements(p_rows) e, jsonb_object_keys(e) k);
 if cols is null then raise exception 'Data % tidak memuat kolom yang dikenal',p_table; end if;
 execute format('insert into public.%I(%s) select %s from jsonb_populate_recordset(null::public.%I,$1)',p_table,cols,cols,p_table) using p_rows;
end $$;

-- restore_backup: ikut memulihkan periode arisan; backup lama tanpa bagian ini dibentuk ulang dari riwayat kocokan.
create or replace function public.restore_backup(p jsonb) returns jsonb language plpgsql security definer set search_path=public set statement_timeout='300s' as $$
declare d jsonb; t text; n jsonb:='{}'::jsonb;
 need text[]:=array['settings','fee_types','members','payments','transactions','events','announcements','albums','photos','draws','activity'];
begin
 perform need_admin();
 perform pg_advisory_xact_lock(hashtext('fh_restore'));
 if p is null or jsonb_typeof(p)<>'object' or p->>'app' is distinct from 'FamilyHub' then raise exception 'Berkas ini bukan backup FamilyHub'; end if;
 if coalesce(nullif(p->>'format','')::int,0)<>1 then raise exception 'Versi format backup tidak didukung'; end if;
 d:=p->'data';
 if d is null or jsonb_typeof(d)<>'object' then raise exception 'Isi backup tidak ditemukan'; end if;
 foreach t in array need loop
  if jsonb_typeof(d->t) is distinct from 'array' then raise exception 'Backup tidak lengkap: bagian "%" tidak ada',t; end if;
 end loop;
 if jsonb_array_length(d->'fee_types')=0 then raise exception 'Backup tidak memuat jenis iuran — berkas diduga rusak'; end if;

 perform set_config('fh.skip_recalc','1',true);
 -- 1) kosongkan (urutan mengikuti ketergantungan kunci asing)
 delete from draws where id is not null;
 delete from arisan_periods where id is not null;
 delete from photos where id is not null;
 delete from albums where id is not null;
 delete from transactions where id is not null;
 delete from payments where id is not null;
 delete from members where id is not null;
 delete from events where id is not null;
 delete from announcements where id is not null;
 delete from activity where id is not null;
 delete from fee_types where id is not null;
 -- 2) isi ulang. ID asli dipertahankan sehingga semua relasi tetap utuh
 insert into settings(k,v) select e->>'k',e->>'v' from jsonb_array_elements(d->'settings') e
  where e->>'k' is not null and e->>'v' is not null and e->>'k'<>'last_backup_at'
  on conflict(k) do update set v=excluded.v;
 foreach t in array array['fee_types','members','payments','transactions','events','announcements','albums','photos','draws'] loop
  perform public._restore_rows(t,d->t);
 end loop;
 -- periode arisan (backup lama belum memuatnya: dibentuk ulang dari riwayat kocokan)
 if jsonb_typeof(d->'arisan_periods')='array' then perform public._restore_rows('arisan_periods',d->'arisan_periods'); end if;
 perform public._ensure_periods();
 -- log aktivitas: buang noise dari trigger, lalu pakai log asli dari backup
 delete from activity where id is not null;
 perform public._restore_rows('activity',d->'activity');
 -- 3) sinkronkan penghitung ID agar data baru tidak bentrok
 foreach t in array array['members','payments','transactions','events','announcements','albums','photos','draws','activity','arisan_periods'] loop
  execute format('select setval(pg_get_serial_sequence(%L,%L),greatest(coalesce((select max(id) from public.%I),0),1),coalesce((select max(id) from public.%I),0)>0)','public.'||t,'id',t,t);
 end loop;
 perform set_config('fh.skip_recalc','0',true);
 perform public.recalc_generations();
 foreach t in array need loop n:=n||jsonb_build_object(t,jsonb_array_length(d->t)); end loop;
 perform log_act('♻','Data dipulihkan dari backup','dibuat '||coalesce(p->>'created_at','?'));
 return n;
end $$;

-- reset_data: reset arisan/anggota/semua juga mengosongkan periode lalu membuka periode bulan kalender ini.
create or replace function public.reset_data(p_scope text,p_keep_settings boolean default true) returns jsonb language plpgsql security definer set search_path=public set statement_timeout='300s' as $$
declare n jsonb:='{}'::jsonb; c bigint; t text; lbl text;
begin
 perform need_admin();
 if p_scope is null or p_scope not in('keuangan','arisan','agenda','pengumuman','galeri','aktivitas','anggota','semua') then raise exception 'Jenis reset tidak dikenal'; end if;
 perform pg_advisory_xact_lock(hashtext('fh_reset'));
 perform set_config('fh.skip_recalc','1',true);

 if p_scope in('arisan','anggota','semua') then
  select count(*) into c from draws; n:=n||jsonb_build_object('draws',c);
  delete from draws where id is not null;
  update settings set v='1' where k='cycle';
  select count(*) into c from arisan_periods; n:=n||jsonb_build_object('arisan_periods',c);
  delete from arisan_periods where id is not null;      -- periode & riwayat pengocokan satu paket
  perform public._ensure_periods();                     -- periode aktif baru = bulan kalender saat ini
 end if;

 if p_scope in('keuangan','anggota','semua') then
  select count(*) into c from payments; n:=n||jsonb_build_object('payments',c);
  if p_scope='anggota' then       -- catatan kas manual tetap ada; yang terkait anggota ikut dibersihkan
   select count(*) into c from transactions where category='Pencairan Arisan' or payment_id is not null;
   n:=n||jsonb_build_object('transactions',c);
   delete from payments where id is not null;                       -- transaksi iuran ikut terhapus (cascade)
   delete from transactions where category='Pencairan Arisan';
  else
   select count(*) into c from transactions; n:=n||jsonb_build_object('transactions',c);
   delete from payments where id is not null;
   delete from transactions where id is not null;
  end if;
 end if;

 if p_scope in('anggota','semua') then
  select count(*) into c from members; n:=n||jsonb_build_object('members',c);
  delete from members where id is not null;
 end if;
 if p_scope in('agenda','semua') then
  select count(*) into c from events; n:=n||jsonb_build_object('events',c);
  delete from events where id is not null;
 end if;
 if p_scope in('pengumuman','semua') then
  select count(*) into c from announcements; n:=n||jsonb_build_object('announcements',c);
  delete from announcements where id is not null;
 end if;
 if p_scope in('galeri','semua') then
  select count(*) into c from photos; n:=n||jsonb_build_object('photos',c);
  select count(*) into c from albums; n:=n||jsonb_build_object('albums',c);
  delete from photos where id is not null;
  delete from albums where id is not null;
 end if;
 if p_scope in('aktivitas','semua') then
  select count(*) into c from activity; n:=n||jsonb_build_object('activity',c);
  delete from activity where id is not null;
 end if;

 if p_scope='semua' and not coalesce(p_keep_settings,true) then
  delete from settings where k in('logo','logo_shape','app_name','app_tagline','last_backup_at');
  insert into settings(k,v) values('org_name','Arisan Keluarga'),('treasurer_name',''),('chair_name',''),('iuran','350000'),('disburse_from',cur_period())
   on conflict(k) do update set v=excluded.v;
  update fee_types set name='Iuran Arisan',amount=350000,required_for_draw=true,active=true,start_period=cur_period() where id=1;
  update fee_types set name='Iuran Wajib',amount=50000,required_for_draw=false,active=true,start_period=cur_period() where id=2;
 end if;

 -- Tabel yang kosong: nomor urut kembali ke 1
 foreach t in array array['members','payments','transactions','events','announcements','albums','photos','draws','activity'] loop
  execute format('select case when not exists(select 1 from public.%I) then setval(pg_get_serial_sequence(%L,%L),1,false) end',t,'public.'||t,'id');
 end loop;
 perform set_config('fh.skip_recalc','0',true);

 lbl:=case p_scope when 'keuangan' then 'Keuangan' when 'arisan' then 'Pengocokan arisan' when 'agenda' then 'Agenda'
  when 'pengumuman' then 'Pengumuman' when 'galeri' then 'Dokumentasi' when 'aktivitas' then 'Log aktivitas'
  when 'anggota' then 'Anggota & silsilah' else 'Seluruh data' end;
 perform log_act('⚠','Reset data: '||lbl,'dilakukan oleh admin');
 return n;
end $$;

