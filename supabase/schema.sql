-- ---------- 7. Iuran: daftar, pencatatan, pencairan ----------
-- Daftar per anggota. Iuran 'putaran' mengikuti p_period (kunci putaran, bawaan = putaran aktif); iuran 'bulanan' mengikuti p_month (bawaan = bulan acuan).
drop function if exists public.get_payments(text);
drop function if exists public.get_payments__impl(text);
create or replace function public.get_payments(p_period text default null,p_month text default null) returns jsonb language plpgsql stable security definer set search_path=public as $$
declare rk text:=coalesce(nullif(trim(p_period),''),cur_period()); mk text:=coalesce(nullif(trim(p_month),''),ref_month(cur_period()));
begin
 perform need_approved();
 if mk !~ '^\d{4}-(0[1-9]|1[0-2])$' then raise exception 'Bulan tidak valid'; end if;
 return jsonb_build_object('period',rk,'month',mk,'round',round_info(rk),'rounds',rounds_brief(),'iuran',(select amount from fee_types where id=1),
  'types',coalesce((select jsonb_agg(to_jsonb(f) order by f.sort,f.id) from fee_types f where f.active),'[]'::jsonb),
  'rows',coalesce((select jsonb_agg(jsonb_build_object('member_id',m.id,'name',m.name,'relation',m.relation,'phone',m.phone,
     'paid',coalesce((select jsonb_object_agg(py.fee_type_id::text,jsonb_build_object('pid',py.id,'amount',py.amount,'paid_at',py.paid_at,'receipt_no',py.receipt_no,'method',py.method))
         from payments py join fee_types ft on ft.id=py.fee_type_id where py.member_id=m.id and py.period=case when ft.schedule='putaran' then rk else mk end),'{}'::jsonb),
     'can_draw',not exists(select 1 from fee_types f where f.active and f.required_for_draw and not exists(select 1 from payments y where y.member_id=m.id and y.fee_type_id=f.id and y.period=case when f.schedule='putaran' then rk else mk end))
    ) order by m.name) from members m where m.active=1),'[]'::jsonb));
end $$;

create or replace function public.record_payment(p_member bigint,p_period text,p_type smallint default 1,p_method text default 'Tunai') returns jsonb language plpgsql security definer set search_path=public as $$
declare m members; f fee_types; r arisan_rounds; pid bigint; rn text; lbl text;
begin
 perform need_admin();
 select * into m from members where id=p_member and active=1; if not found then raise exception 'Anggota tidak ditemukan atau nonaktif'; end if;
 select * into f from fee_types where id=p_type and active; if not found then raise exception 'Jenis iuran tidak ditemukan atau tidak aktif'; end if;
 p_period:=trim(p_period);
 if p_period is null or p_period='' then raise exception 'Periode tidak valid'; end if;
 if f.schedule='putaran' then
  select * into r from arisan_rounds where period=p_period; if not found then raise exception 'Putaran arisan tidak ditemukan'; end if;
  if r.status='rencana' then raise exception 'Putaran % belum dibuka. Buka putaran dulu agar iuran bisa dicatat.',r.seq; end if;
  if r.status='batal' then raise exception 'Putaran % sudah dibatalkan',r.seq; end if;
  if to_char(round_ref(r),'YYYY-MM')<f.start_period then raise exception '% baru berlaku mulai %',f.name,f.start_period; end if;
  lbl:='Putaran '||r.seq;
 else
  if p_period !~ '^\d{4}-(0[1-9]|1[0-2])$' then raise exception 'Periode tidak valid'; end if;
  if p_period<f.start_period then raise exception '% baru berlaku mulai %',f.name,f.start_period; end if;
  if p_period>to_char((now() at time zone 'Asia/Jakarta')+interval '12 months','YYYY-MM') then raise exception 'Periode terlalu jauh ke depan (maksimal 12 bulan)'; end if;
  lbl:=p_period;
 end if;
 if p_method not in('Tunai','Transfer','Lainnya') then raise exception 'Metode pembayaran tidak valid'; end if;
 if exists(select 1 from payments where member_id=p_member and period=p_period and fee_type_id=p_type) then raise exception '% (%) untuk % sudah tercatat',f.name,lbl,m.name; end if;
 insert into payments(member_id,period,amount,fee_type_id,method) values(p_member,p_period,f.amount,p_type,p_method) returning id,receipt_no into pid,rn;
 insert into transactions(date,description,type,amount,payment_id) values((now() at time zone 'Asia/Jakarta')::date,f.name||' '||lbl||' - '||m.name,'masuk',f.amount,pid);
 perform log_act('✓',m.name||' membayar '||lower(f.name),'Rp '||to_char(f.amount,'FM999G999G999')||' • '||lbl||' • '||rn);
 return jsonb_build_object('id',pid,'receipt_no',rn,'amount',f.amount,'period',p_period);
end $$;

create or replace function public.disburse_arisan(p_period text default null) returns jsonb language plpgsql security definer set search_path=public as $$
declare p text:=coalesce(p_period,cur_period()); d draws; coll bigint; disb bigint; amt bigint; tid bigint;
begin
 perform need_admin();
 perform pg_advisory_xact_lock(hashtext('fh_disburse'));
 if p is null then raise exception 'Belum ada putaran arisan aktif'; end if;
 select * into d from draws where period=p and status='sah'; if not found then raise exception 'Belum ada pemenang yang disahkan untuk %',period_label(p); end if;
 select coalesce(sum(y.amount),0) into coll from payments y join fee_types f on f.id=y.fee_type_id where y.period=p and f.fund='arisan';
 select coalesce(sum(amount),0) into disb from transactions where category='Pencairan Arisan' and period=p;
 amt:=coll-disb;
 if amt<=0 then raise exception 'Tidak ada dana arisan yang tersisa untuk dicairkan pada %',period_label(p); end if;
 insert into transactions(date,description,type,amount,fund,category,period,member_id)
  values((now() at time zone 'Asia/Jakarta')::date,case when disb>0 then 'Pencairan susulan arisan ' else 'Pencairan arisan ' end||period_label(p)||' - '||d.winner_name,'keluar',amt,'arisan','Pencairan Arisan',p,d.winner_id) returning id into tid;
 perform log_act('💸','Dana arisan '||period_label(p)||' dicairkan ke '||d.winner_name,'Rp '||to_char(amt,'FM999G999G999'));
 return jsonb_build_object('id',tid,'amount',amt,'winner',d.winner_name,'period',p);
end $$;

-- ---------- 8. Tunggakan & laporan ----------
-- Tunggakan iuran 'bulanan' = bulan (sejak berlaku s.d. bulan lalu) yang belum dibayar.
-- Tunggakan iuran 'putaran' = putaran yang SUDAH SELESAI dan belum dibayar. Bulan tanpa arisan tidak menunggak.
create or replace function public.iuran_arrears(p_type smallint default null,p_include_current boolean default false) returns jsonb language plpgsql stable security definer set search_path=public as $$
begin
 perform need_approved();
 return coalesce((select jsonb_agg(to_jsonb(r) order by r.name,r.type_id) from (
  select m.id member_id,m.name,m.phone,f.id type_id,f.name type_name,f.amount,f.schedule,
         array_agg(g.period order by g.ord) periods,count(*)::int n,(count(*)*f.amount)::bigint total
  from fee_types f cross join members m
  cross join lateral (
    select to_char(d,'YYYY-MM') period,to_char(d,'YYYY-MM') ord,extract(year from d)::int yr
      from generate_series(to_date(f.start_period||'-01','YYYY-MM-DD'),
           to_date(calendar_period()||'-01','YYYY-MM-DD')-case when p_include_current then interval '0 month' else interval '1 month' end,interval '1 month') d
     where f.schedule='bulanan'
    union all
    select r.period,lpad(r.seq::text,8,'0'),extract(year from round_ref(r))::int
      from arisan_rounds r where f.schedule='putaran' and (r.status='selesai' or (p_include_current and r.status='aktif')) and to_char(round_ref(r),'YYYY-MM')>=f.start_period) g
  where f.active and m.active=1 and (p_type is null or f.id=p_type) and g.yr>=coalesce(m.joined,0)
    and not exists(select 1 from payments y where y.member_id=m.id and y.fee_type_id=f.id and y.period=g.period)
  group by m.id,m.name,m.phone,f.id,f.name,f.amount,f.schedule) r),'[]'::jsonb);
end $$;

-- Rekap realisasi: iuran bulanan per bulan, iuran putaran per putaran (yang tanggal acuannya jatuh dalam rentang bulan).
create or replace function public.iuran_recap(p_from text,p_to text) returns jsonb language plpgsql stable security definer set search_path=public as $$
begin
 perform need_approved();
 if p_from !~ '^\d{4}-\d{2}$' or p_to !~ '^\d{4}-\d{2}$' then raise exception 'Periode tidak valid'; end if;
 if to_date(p_to||'-01','YYYY-MM-DD')-to_date(p_from||'-01','YYYY-MM-DD')>1100 then raise exception 'Rentang maksimal 36 bulan'; end if;
 return coalesce((select jsonb_agg(to_jsonb(r) order by r.d,r.seq nulls first,r.type_id) from (
  select g.period,f.id type_id,f.code,f.name,f.amount,f.schedule,null::int seq,null::text title,null::date held_on,to_date(g.period||'-01','YYYY-MM-DD') d,
    (select count(*) from members m where m.active=1 and substr(g.period,1,4)::int>=coalesce(m.joined,0))::int members,
    (select count(*) from payments y join members m on m.id=y.member_id and m.active=1 where y.fee_type_id=f.id and y.period=g.period)::int paid,
    coalesce((select sum(y.amount) from payments y where y.fee_type_id=f.id and y.period=g.period),0)::bigint realized
  from fee_types f
  cross join lateral (select to_char(x,'YYYY-MM') period from generate_series(to_date(p_from||'-01','YYYY-MM-DD'),to_date(p_to||'-01','YYYY-MM-DD'),interval '1 month') x) g
  where f.active and f.schedule='bulanan' and g.period>=f.start_period
  union all
  select r.period,f.id,f.code,f.name,f.amount,f.schedule,r.seq,r.title,r.held_on,round_ref(r),
    (select count(*) from members m where m.active=1 and extract(year from round_ref(r))::int>=coalesce(m.joined,0))::int,
    (select count(*) from payments y join members m on m.id=y.member_id and m.active=1 where y.fee_type_id=f.id and y.period=r.period)::int,
    coalesce((select sum(y.amount) from payments y where y.fee_type_id=f.id and y.period=r.period),0)::bigint
  from fee_types f cross join arisan_rounds r
  where f.active and f.schedule='putaran' and r.status in('aktif','selesai')
    and to_char(round_ref(r),'YYYY-MM') between p_from and p_to and to_char(round_ref(r),'YYYY-MM')>=f.start_period) r),'[]'::jsonb);
end $$;

-- Matriks kepatuhan satu tahun. Iuran bulanan: 12 kolom bulan. Iuran putaran: satu kolom per putaran pada tahun itu.
-- Hasil: {schedule, cols:[{key,…}], rows:[{member_id,name,m}]}; m = satu karakter per kolom: 1=lunas 0=belum -=belum berlaku
create or replace function public.compliance_matrix(p_year int,p_type smallint) returns jsonb language plpgsql stable security definer set search_path=public as $$
declare f fee_types; cal text:=calendar_period(); cols jsonb; keys text[];
begin
 perform need_approved();
 select * into f from fee_types where id=p_type; if not found then raise exception 'Jenis iuran tidak ditemukan'; end if;
 if f.schedule='putaran' then
  select coalesce(jsonb_agg(jsonb_build_object('key',x.period,'seq',x.seq,'title',x.title,'held_on',x.held_on,'ref',x.ref,'status',x.status) order by x.ref,x.seq),'[]'::jsonb),
         coalesce(array_agg(x.period order by x.ref,x.seq),'{}'::text[]) into cols,keys
  from (select r.period,r.seq,r.title,r.held_on,r.status,round_ref(r) ref from arisan_rounds r
        where r.status in('aktif','selesai') and extract(year from round_ref(r))::int=p_year and to_char(round_ref(r),'YYYY-MM')>=f.start_period) x;
  return jsonb_build_object('schedule','putaran','cols',cols,'rows',coalesce((select jsonb_agg(jsonb_build_object('member_id',m.id,'name',m.name,'m',(
     select coalesce(string_agg(case when p_year<coalesce(m.joined,0) then '-'
         when exists(select 1 from payments y where y.member_id=m.id and y.fee_type_id=p_type and y.period=u.k) then '1' else '0' end,'' order by u.o),'')
     from unnest(keys) with ordinality u(k,o))) order by m.name) from members m where m.active=1),'[]'::jsonb));
 end if;
 return jsonb_build_object('schedule','bulanan',
  'cols',(select jsonb_agg(jsonb_build_object('key',p_year::text||'-'||lpad(g::text,2,'0')) order by g) from generate_series(1,12) g),
  'rows',coalesce((select jsonb_agg(jsonb_build_object('member_id',m.id,'name',m.name,'m',(
     select string_agg(case when per<f.start_period or per>cal or substr(per,1,4)::int<coalesce(m.joined,0) then '-'
                            when exists(select 1 from payments y where y.member_id=m.id and y.fee_type_id=p_type and y.period=per) then '1' else '0' end,'' order by g)
     from generate_series(1,12) g cross join lateral (select p_year::text||'-'||lpad(g::text,2,'0') per) q)) order by m.name) from members m where m.active=1),'[]'::jsonb));
end $$;

