-- ---------- 5. Mengelola putaran (hanya admin) ----------
create or replace function public._round_check(t text,held date,pl text,nt text,req bigint) returns void language plpgsql security definer set search_path=public as $$
begin
 if t is not null and char_length(t)>80 then raise exception 'Judul putaran maksimal 80 karakter'; end if;
 if pl is not null and char_length(pl)>120 then raise exception 'Tempat maksimal 120 karakter'; end if;
 if nt is not null and char_length(nt)>500 then raise exception 'Catatan maksimal 500 karakter'; end if;
 if held is not null and (held<date '2000-01-01' or held>(now() at time zone 'Asia/Jakarta')::date+1100) then raise exception 'Tanggal putaran tidak wajar (maksimal 3 tahun ke depan)'; end if;
 if req is not null and not exists(select 1 from members where id=req) then raise exception 'Anggota peminta tidak ditemukan'; end if;
end $$;

create or replace function public.create_round(p_title text default null,p_held_on date default null,p_place text default null,p_requested_by bigint default null,p_note text default null) returns jsonb language plpgsql security definer set search_path=public as $$
declare t text:=nullif(trim(p_title),''); pl text:=nullif(trim(p_place),''); nt text:=nullif(trim(p_note),''); s int; k text; who text; rid bigint;
begin
 perform need_admin();
 perform pg_advisory_xact_lock(hashtext('fh_run_draw'));
 perform _round_check(t,p_held_on,pl,nt,p_requested_by);
 select name into who from profiles where id=auth.uid();
 select coalesce(max(seq),0)+1 into s from arisan_rounds;
 k:='P'||lpad(s::text,3,'0');
 insert into arisan_rounds(seq,period,title,status,held_on,place,requested_by,note,created_by) values(s,k,t,'rencana',p_held_on,pl,p_requested_by,nt,coalesce(who,'admin')) returning id into rid;
 perform log_act('📅','Putaran arisan '||s||' dijadwalkan',coalesce(to_char(p_held_on,'DD-MM-YYYY'),'tanggal belum pasti')||coalesce(' • '||pl,'')||coalesce(' • '||t,''));
 return jsonb_build_object('id',rid,'seq',s,'period',k);
end $$;

create or replace function public.update_round(p_id bigint,p_title text default null,p_held_on date default null,p_place text default null,p_requested_by bigint default null,p_note text default null) returns void language plpgsql security definer set search_path=public as $$
declare t text:=nullif(trim(p_title),''); pl text:=nullif(trim(p_place),''); nt text:=nullif(trim(p_note),''); r arisan_rounds;
begin
 perform need_admin();
 perform pg_advisory_xact_lock(hashtext('fh_run_draw'));
 select * into r from arisan_rounds where id=p_id for update; if not found then raise exception 'Putaran tidak ditemukan'; end if;
 if r.status='batal' then raise exception 'Putaran % sudah dibatalkan dan tidak bisa diubah',r.seq; end if;
 perform _round_check(t,p_held_on,pl,nt,p_requested_by);
 update arisan_rounds set title=t,held_on=p_held_on,place=pl,requested_by=p_requested_by,note=nt where id=p_id;
 perform log_act('✎','Putaran arisan '||r.seq||' diubah',coalesce(to_char(p_held_on,'DD-MM-YYYY'),'tanggal belum pasti')||coalesce(' • '||pl,''));
end $$;

-- Menutup putaran aktif dengan pemeriksaan yang sama seperti sebelumnya (pemenang sah, atau alasan tertulis). NULL bila tak ada putaran aktif.
create or replace function public._close_active(p_note text,p_force boolean) returns text language plpgsql security definer set search_path=public as $$
declare cur arisan_rounds; who text;
begin
 select * into cur from arisan_rounds where status='aktif' for update;
 if not found then return null; end if;
 if exists(select 1 from draws where period=cur.period and status='menunggu') then
  raise exception 'Putaran % masih punya pemenang yang menunggu konfirmasi kehadiran. Selesaikan dulu di pengocokan.',cur.seq; end if;
 if not exists(select 1 from draws where period=cur.period and status='sah') then
  if not coalesce(p_force,false) then raise exception 'Putaran % belum punya pemenang yang disahkan. Sahkan pemenang dulu, atau tutup tanpa pemenang dengan alasan tertulis.',cur.seq; end if;
  if coalesce(trim(p_note),'')='' then raise exception 'Alasan wajib diisi bila putaran ditutup tanpa pemenang'; end if;
 end if;
 select name into who from profiles where id=auth.uid();
 update arisan_rounds set status='selesai',closed_at=now(),closed_by=coalesce(who,'admin'),close_note=nullif(trim(p_note),'') where id=cur.id;
 return cur.period;
end $$;

-- Membuka putaran (dari 'rencana', atau membuka kembali yang 'selesai' untuk koreksi). Putaran aktif sebelumnya ditutup otomatis.
create or replace function public.open_round(p_id bigint,p_note text default null,p_force boolean default false) returns jsonb language plpgsql security definer set search_path=public as $$
declare tgt arisan_rounds; closed text; who text;
begin
 perform need_admin();
 perform pg_advisory_xact_lock(hashtext('fh_run_draw'));       -- sejajar dengan run_draw
 select * into tgt from arisan_rounds where id=p_id for update; if not found then raise exception 'Putaran tidak ditemukan'; end if;
 if tgt.status='aktif' then raise exception 'Putaran % sudah aktif',tgt.seq; end if;
 if tgt.status='batal' then raise exception 'Putaran % sudah dibatalkan dan tidak bisa dibuka',tgt.seq; end if;
 closed:=_close_active(p_note,p_force);
 select name into who from profiles where id=auth.uid();
 update arisan_rounds set status='aktif',opened_at=case when tgt.status='rencana' then now() else coalesce(opened_at,now()) end,opened_by=case when tgt.status='rencana' then coalesce(who,'admin') else coalesce(opened_by,coalesce(who,'admin')) end,
   closed_at=null,closed_by=null,close_note=null where id=tgt.id;       -- (jejak penutupan lama tersimpan di audit_log)
 perform log_act('📅','Putaran arisan '||tgt.seq||case when tgt.status='selesai' then ' dibuka kembali' else ' dibuka' end,
   case when closed is not null then 'putaran '||period_label(closed)||' ditutup' else 'tanpa putaran aktif sebelumnya' end);
 return jsonb_build_object('active',tgt.period,'seq',tgt.seq,'closed',closed,'reopened',tgt.status='selesai');
end $$;

-- Menutup putaran aktif tanpa membuka yang lain (arisan jeda sampai ada permintaan berikutnya).
create or replace function public.close_round(p_note text default null,p_force boolean default false) returns jsonb language plpgsql security definer set search_path=public as $$
declare k text;
begin
 perform need_admin();
 perform pg_advisory_xact_lock(hashtext('fh_run_draw'));
 k:=_close_active(p_note,p_force);
 if k is null then raise exception 'Tidak ada putaran yang sedang aktif'; end if;
 perform log_act('📅',period_label(k)||' ditutup','arisan jeda sampai putaran berikutnya dibuka');
 return jsonb_build_object('closed',k);
end $$;

-- Membatalkan putaran yang tidak jadi digelar. Hanya bila belum ada pembayaran & pengocokan (jangan ada uang/riwayat yang menggantung).
create or replace function public.cancel_round(p_id bigint,p_reason text default null) returns void language plpgsql security definer set search_path=public as $$
declare tgt arisan_rounds; who text;
begin
 perform need_admin();
 perform pg_advisory_xact_lock(hashtext('fh_run_draw'));
 select * into tgt from arisan_rounds where id=p_id for update; if not found then raise exception 'Putaran tidak ditemukan'; end if;
 if tgt.status='batal' then raise exception 'Putaran % sudah dibatalkan',tgt.seq; end if;
 if exists(select 1 from draws where period=tgt.period) then raise exception 'Putaran % sudah punya riwayat pengocokan sehingga tidak bisa dibatalkan',tgt.seq; end if;
 if exists(select 1 from payments y join fee_types f on f.id=y.fee_type_id where y.period=tgt.period and f.schedule='putaran') then
  raise exception 'Putaran % sudah punya pembayaran iuran. Batalkan pembayarannya dulu (menu Iuran) bila putaran memang tidak jadi.',tgt.seq; end if;
 if tgt.status<>'rencana' and coalesce(trim(p_reason),'')='' then raise exception 'Alasan pembatalan wajib diisi'; end if;
 select name into who from profiles where id=auth.uid();
 update arisan_rounds set status='batal',closed_at=now(),closed_by=coalesce(who,'admin'),close_note=nullif(trim(p_reason),'') where id=p_id;
 perform log_act('✗','Putaran arisan '||tgt.seq||' dibatalkan',coalesce(nullif(trim(p_reason),''),'tanpa keterangan'));
end $$;

-- Ringkasan untuk layar "Kelola putaran"
create or replace function public.round_state() returns jsonb language plpgsql stable security definer set search_path=public as $$
begin
 perform need_approved();
 return jsonb_build_object('active',cur_period(),'next_seq',coalesce((select max(seq) from arisan_rounds),0)+1,'today',(now() at time zone 'Asia/Jakarta')::date,
  'rows',coalesce((select jsonb_agg(to_jsonb(x) order by x.seq desc) from (
    select r.id,r.seq,r.period,r.title,r.status,r.held_on,r.place,r.requested_by,(select m.name from members m where m.id=r.requested_by) requester,r.note,
      r.opened_at,r.opened_by,r.closed_at,r.closed_by,r.close_note,
      (select count(*) from draws d where d.period=r.period)::int attempts,
      (select d.winner_name from draws d where d.period=r.period and d.status='sah') winner,
      (select count(*) from draws d where d.period=r.period and d.status='menunggu')::int pending,
      (select count(*) from payments y join fee_types f on f.id=y.fee_type_id where y.period=r.period and f.fund='arisan')::int paid,
      coalesce((select sum(y.amount) from payments y join fee_types f on f.id=y.fee_type_id where y.period=r.period and f.fund='arisan'),0)::bigint collected,
      coalesce((select sum(t.amount) from transactions t where t.category='Pencairan Arisan' and t.period=r.period),0)::bigint disbursed
    from arisan_rounds r) x),'[]'::jsonb));
end $$;

-- ---------- 6. Konfigurasi & jenis iuran ----------
create or replace function public.fee_config() returns jsonb language plpgsql stable security definer set search_path=public as $$
begin
 perform need_approved();
 return jsonb_build_object('period',cur_period(),'round',round_info(cur_period()),'rounds',rounds_brief(),'month',calendar_period(),'ref_month',ref_month(cur_period()),
  'types',coalesce((select jsonb_agg(to_jsonb(f) order by f.sort,f.id) from fee_types f),'[]'::jsonb),
  'meta',jsonb_build_object('org',coalesce(cfg('org_name'),'Arisan Keluarga'),'treasurer',coalesce(cfg('treasurer_name'),''),'chair',coalesce(cfg('chair_name'),'')));
end $$;

drop function if exists public.set_fee_type(smallint,text,int,boolean,boolean,text);
create or replace function public.set_fee_type(p_id smallint,p_name text,p_amount int,p_required boolean,p_active boolean,p_start text,p_schedule text default null) returns void language plpgsql security definer set search_path=public as $$
declare f fee_types; sch text;
begin
 perform need_admin();
 select * into f from fee_types where id=p_id; if not found then raise exception 'Jenis iuran tidak ditemukan'; end if;
 if p_amount is null or p_amount<=0 then raise exception 'Nominal iuran tidak valid'; end if;
 if coalesce(trim(p_name),'')='' then raise exception 'Nama iuran wajib diisi'; end if;
 if p_start !~ '^\d{4}-\d{2}$' then raise exception 'Periode mulai tidak valid'; end if;
 sch:=coalesce(p_schedule,f.schedule);
 if sch not in('bulanan','putaran') then raise exception 'Jadwal iuran tidak valid'; end if;
 if f.fund='arisan' then sch:='putaran'; end if;
 if sch<>f.schedule and exists(select 1 from payments where fee_type_id=p_id) then
  raise exception 'Jadwal % tidak bisa diubah karena sudah ada pembayaran tercatat. Nonaktifkan iuran ini bila ingin berhenti menagih.',f.name; end if;
 update fee_types set name=trim(p_name),amount=p_amount,required_for_draw=coalesce(p_required,false),active=coalesce(p_active,true),start_period=p_start,schedule=sch where id=p_id;
 if p_id=1 then update settings set v=p_amount::text where k='iuran'; end if;
 perform log_act('⚙','Pengaturan '||lower(trim(p_name))||' diubah','Rp '||to_char(p_amount,'FM999G999G999')||case when sch='putaran' then '/putaran' else '/bulan' end);
end $$;

-- ---------- 7. Iuran: daftar, pencatatan, pencairan ----------
-- Daftar per anggota. Iuran 'putaran' mengikuti p_period (kunci putaran, bawaan = putaran aktif); iuran 'bulanan' mengikuti p_month (bawaan = bulan acuan).
drop function if exists public.get_payments(text);
drop function if exists public.get_payments__impl(text);
create or replace function public.get_payments(p_period text default null,p_month text default null) returns jsonb language plpgsql stable security definer set search_path=public as $$
declare rk text:=coalesce(nullif(trim(p_period),''),cur_period()); mk text:=coalesce(nullif(trim(p_month),''),ref_month(cur_period()));
begin
 perform need_approved();
 if mk !~ '^\d{4}-(0[1-9]|1[0-2])$' then raise exception 'Bulan tidak valid'; end if;
 return jsonb_build_object('period',rk,'month',mk,'round',round_info(rk),'rounds',rounds_brief(),'iuran',(select amount from fee_types where id=1),
  'types',coalesce((select jsonb_agg(to_jsonb(f) order by f.sort,f.id) from fee_types f where f.active),'[]'::jsonb),
  'rows',coalesce((select jsonb_agg(jsonb_build_object('member_id',m.id,'name',m.name,'relation',m.relation,'phone',m.phone,
     'paid',coalesce((select jsonb_object_agg(py.fee_type_id::text,jsonb_build_object('pid',py.id,'amount',py.amount,'paid_at',py.paid_at,'receipt_no',py.receipt_no,'method',py.method))
         from payments py join fee_types ft on ft.id=py.fee_type_id where py.member_id=m.id and py.period=case when ft.schedule='putaran' then rk else mk end),'{}'::jsonb),
     'can_draw',not exists(select 1 from fee_types f where f.active and f.required_for_draw and not exists(select 1 from payments y where y.member_id=m.id and y.fee_type_id=f.id and y.period=case when f.schedule='putaran' then rk else mk end))
    ) order by m.name) from members m where m.active=1),'[]'::jsonb));
end $$;

create or replace function public.record_payment(p_member bigint,p_period text,p_type smallint default 1,p_method text default 'Tunai') returns jsonb language plpgsql security definer set search_path=public as $$
declare m members; f fee_types; r arisan_rounds; pid bigint; rn text; lbl text;
begin
 perform need_admin();
 select * into m from members where id=p_member and active=1; if not found then raise exception 'Anggota tidak ditemukan atau nonaktif'; end if;
 select * into f from fee_types where id=p_type and active; if not found then raise exception 'Jenis iuran tidak ditemukan atau tidak aktif'; end if;
 p_period:=trim(p_period);
 if p_period is null or p_period='' then raise exception 'Periode tidak valid'; end if;
 if f.schedule='putaran' then
  select * into r from arisan_rounds where period=p_period; if not found then raise exception 'Putaran arisan tidak ditemukan'; end if;
  if r.status='rencana' then raise exception 'Putaran % belum dibuka. Buka putaran dulu agar iuran bisa dicatat.',r.seq; end if;
  if r.status='batal' then raise exception 'Putaran % sudah dibatalkan',r.seq; end if;
  if to_char(round_ref(r),'YYYY-MM')<f.start_period then raise exception '% baru berlaku mulai %',f.name,f.start_period; end if;
  lbl:='Putaran '||r.seq;
 else
  if p_period !~ '^\d{4}-(0[1-9]|1[0-2])$' then raise exception 'Periode tidak valid'; end if;
  if p_period<f.start_period then raise exception '% baru berlaku mulai %',f.name,f.start_period; end if;
  if p_period>to_char((now() at time zone 'Asia/Jakarta')+interval '12 months','YYYY-MM') then raise exception 'Periode terlalu jauh ke depan (maksimal 12 bulan)'; end if;
  lbl:=p_period;
 end if;
 if p_method not in('Tunai','Transfer','Lainnya') then raise exception 'Metode pembayaran tidak valid'; end if;
 if exists(select 1 from payments where member_id=p_member and period=p_period and fee_type_id=p_type) then raise exception '% (%) untuk % sudah tercatat',f.name,lbl,m.name; end if;
 insert into payments(member_id,period,amount,fee_type_id,method) values(p_member,p_period,f.amount,p_type,p_method) returning id,receipt_no into pid,rn;
 insert into transactions(date,description,type,amount,payment_id) values((now() at time zone 'Asia/Jakarta')::date,f.name||' '||lbl||' - '||m.name,'masuk',f.amount,pid);
 perform log_act('✓',m.name||' membayar '||lower(f.name),'Rp '||to_char(f.amount,'FM999G999G999')||' • '||lbl||' • '||rn);
 return jsonb_build_object('id',pid,'receipt_no',rn,'amount',f.amount,'period',p_period);
end $$;

create or replace function public.disburse_arisan(p_period text default null) returns jsonb language plpgsql security definer set search_path=public as $$
declare p text:=coalesce(p_period,cur_period()); d draws; coll bigint; disb bigint; amt bigint; tid bigint;
begin
 perform need_admin();
 perform pg_advisory_xact_lock(hashtext('fh_disburse'));
 if p is null then raise exception 'Belum ada putaran arisan aktif'; end if;
 select * into d from draws where period=p and status='sah'; if not found then raise exception 'Belum ada pemenang yang disahkan untuk %',period_label(p); end if;
 select coalesce(sum(y.amount),0) into coll from payments y join fee_types f on f.id=y.fee_type_id where y.period=p and f.fund='arisan';
 select coalesce(sum(amount),0) into disb from transactions where category='Pencairan Arisan' and period=p;
 amt:=coll-disb;
 if amt<=0 then raise exception 'Tidak ada dana arisan yang tersisa untuk dicairkan pada %',period_label(p); end if;
 insert into transactions(date,description,type,amount,fund,category,period,member_id)
  values((now() at time zone 'Asia/Jakarta')::date,case when disb>0 then 'Pencairan susulan arisan ' else 'Pencairan arisan ' end||period_label(p)||' - '||d.winner_name,'keluar',amt,'arisan','Pencairan Arisan',p,d.winner_id) returning id into tid;
 perform log_act('💸','Dana arisan '||period_label(p)||' dicairkan ke '||d.winner_name,'Rp '||to_char(amt,'FM999G999G999'));
 return jsonb_build_object('id',tid,'amount',amt,'winner',d.winner_name,'period',p);
end $$;

-- ---------- 8. Tunggakan & laporan ----------
-- Tunggakan iuran 'bulanan' = bulan (sejak berlaku s.d. bulan lalu) yang belum dibayar.
-- Tunggakan iuran 'putaran' = putaran yang SUDAH SELESAI dan belum dibayar. Bulan tanpa arisan tidak menunggak.
create or replace function public.iuran_arrears(p_type smallint default null,p_include_current boolean default false) returns jsonb language plpgsql stable security definer set search_path=public as $$
begin
 perform need_approved();
 return coalesce((select jsonb_agg(to_jsonb(r) order by r.name,r.type_id) from (
  select m.id member_id,m.name,m.phone,f.id type_id,f.name type_name,f.amount,f.schedule,
         array_agg(g.period order by g.ord) periods,count(*)::int n,(count(*)*f.amount)::bigint total
  from fee_types f cross join members m
  cross join lateral (
    select to_char(d,'YYYY-MM') period,to_char(d,'YYYY-MM') ord,extract(year from d)::int yr
      from generate_series(to_date(f.start_period||'-01','YYYY-MM-DD'),
           to_date(calendar_period()||'-01','YYYY-MM-DD')-case when p_include_current then interval '0 month' else interval '1 month' end,interval '1 month') d
     where f.schedule='bulanan'
    union all
    select r.period,lpad(r.seq::text,8,'0'),extract(year from round_ref(r))::int
      from arisan_rounds r where f.schedule='putaran' and (r.status='selesai' or (p_include_current and r.status='aktif')) and to_char(round_ref(r),'YYYY-MM')>=f.start_period) g
  where f.active and m.active=1 and (p_type is null or f.id=p_type) and g.yr>=coalesce(m.joined,0)
    and not exists(select 1 from payments y where y.member_id=m.id and y.fee_type_id=f.id and y.period=g.period)
  group by m.id,m.name,m.phone,f.id,f.name,f.amount,f.schedule) r),'[]'::jsonb);
end $$;

-- Rekap realisasi: iuran bulanan per bulan, iuran putaran per putaran (yang tanggal acuannya jatuh dalam rentang bulan).
create or replace function public.iuran_recap(p_from text,p_to text) returns jsonb language plpgsql stable security definer set search_path=public as $$
begin
 perform need_approved();
 if p_from !~ '^\d{4}-\d{2}$' or p_to !~ '^\d{4}-\d{2}$' then raise exception 'Periode tidak valid'; end if;
 if to_date(p_to||'-01','YYYY-MM-DD')-to_date(p_from||'-01','YYYY-MM-DD')>1100 then raise exception 'Rentang maksimal 36 bulan'; end if;
 return coalesce((select jsonb_agg(to_jsonb(r) order by r.d,r.seq nulls first,r.type_id) from (
  select g.period,f.id type_id,f.code,f.name,f.amount,f.schedule,null::int seq,null::text title,null::date held_on,to_date(g.period||'-01','YYYY-MM-DD') d,
    (select count(*) from members m where m.active=1 and substr(g.period,1,4)::int>=coalesce(m.joined,0))::int members,
    (select count(*) from payments y join members m on m.id=y.member_id and m.active=1 where y.fee_type_id=f.id and y.period=g.period)::int paid,
    coalesce((select sum(y.amount) from payments y where y.fee_type_id=f.id and y.period=g.period),0)::bigint realized
  from fee_types f
  cross join lateral (select to_char(x,'YYYY-MM') period from generate_series(to_date(p_from||'-01','YYYY-MM-DD'),to_date(p_to||'-01','YYYY-MM-DD'),interval '1 month') x) g
  where f.active and f.schedule='bulanan' and g.period>=f.start_period
  union all
  select r.period,f.id,f.code,f.name,f.amount,f.schedule,r.seq,r.title,r.held_on,round_ref(r),
    (select count(*) from members m where m.active=1 and extract(year from round_ref(r))::int>=coalesce(m.joined,0))::int,
    (select count(*) from payments y join members m on m.id=y.member_id and m.active=1 where y.fee_type_id=f.id and y.period=r.period)::int,
    coalesce((select sum(y.amount) from payments y where y.fee_type_id=f.id and y.period=r.period),0)::bigint
  from fee_types f cross join arisan_rounds r
  where f.active and f.schedule='putaran' and r.status in('aktif','selesai')
    and to_char(round_ref(r),'YYYY-MM') between p_from and p_to and to_char(round_ref(r),'YYYY-MM')>=f.start_period) r),'[]'::jsonb);
end $$;

-- Matriks kepatuhan satu tahun. Iuran bulanan: 12 kolom bulan. Iuran putaran: satu kolom per putaran pada tahun itu.
-- Hasil: {schedule, cols:[{key,…}], rows:[{member_id,name,m}]}; m = satu karakter per kolom: 1=lunas 0=belum -=belum berlaku
create or replace function public.compliance_matrix(p_year int,p_type smallint) returns jsonb language plpgsql stable security definer set search_path=public as $$
declare f fee_types; cal text:=calendar_period(); cols jsonb; keys text[];
begin
 perform need_approved();
 select * into f from fee_types where id=p_type; if not found then raise exception 'Jenis iuran tidak ditemukan'; end if;
 if f.schedule='putaran' then
  select coalesce(jsonb_agg(jsonb_build_object('key',x.period,'seq',x.seq,'title',x.title,'held_on',x.held_on,'ref',x.ref,'status',x.status) order by x.ref,x.seq),'[]'::jsonb),
         coalesce(array_agg(x.period order by x.ref,x.seq),'{}'::text[]) into cols,keys
  from (select r.period,r.seq,r.title,r.held_on,r.status,round_ref(r) ref from arisan_rounds r
        where r.status in('aktif','selesai') and extract(year from round_ref(r))::int=p_year and to_char(round_ref(r),'YYYY-MM')>=f.start_period) x;
  return jsonb_build_object('schedule','putaran','cols',cols,'rows',coalesce((select jsonb_agg(jsonb_build_object('member_id',m.id,'name',m.name,'m',(
     select coalesce(string_agg(case when p_year<coalesce(m.joined,0) then '-'
         when exists(select 1 from payments y where y.member_id=m.id and y.fee_type_id=p_type and y.period=u.k) then '1' else '0' end,'' order by u.o),'')
     from unnest(keys) with ordinality u(k,o))) order by m.name) from members m where m.active=1),'[]'::jsonb));
 end if;
 return jsonb_build_object('schedule','bulanan',
  'cols',(select jsonb_agg(jsonb_build_object('key',p_year::text||'-'||lpad(g::text,2,'0')) order by g) from generate_series(1,12) g),
  'rows',coalesce((select jsonb_agg(jsonb_build_object('member_id',m.id,'name',m.name,'m',(
     select string_agg(case when per<f.start_period or per>cal or substr(per,1,4)::int<coalesce(m.joined,0) then '-'
                            when exists(select 1 from payments y where y.member_id=m.id and y.fee_type_id=p_type and y.period=per) then '1' else '0' end,'' order by g)
     from generate_series(1,12) g cross join lateral (select p_year::text||'-'||lpad(g::text,2,'0') per) q)) order by m.name) from members m where m.active=1),'[]'::jsonb));
end $$;

-- ---------- 9. Dashboard keuangan, kelayakan kocok, status pengocokan ----------
create or replace function public.finance_dashboard() returns jsonb language plpgsql stable security definer set search_path=public as $$
declare cp text:=cur_period(); cal text:=calendar_period(); r jsonb; dseq int:=coalesce(nullif(cfg('disburse_from_seq'),'')::int,1);
begin
 perform need_approved();
 r:=jsonb_build_object('period',cp,'round',round_info(cp),'rounds',rounds_brief(),'month_key',cal,
  'funds',(select jsonb_agg(jsonb_build_object('fund',v.fund,'saldo',coalesce((select sum(case when type='masuk' then amount else -amount end) from transactions t where t.fund=v.fund),0)::bigint) order by v.ord) from (values('arisan',1),('kas',2)) v(fund,ord)),
  'month',(select jsonb_build_object('masuk',coalesce(sum(amount) filter(where type='masuk'),0)::bigint,'keluar',coalesce(sum(amount) filter(where type='keluar'),0)::bigint) from transactions where to_char(date,'YYYY-MM')=cal),
  'types',coalesce((select jsonb_agg(jsonb_build_object('id',f.id,'code',f.code,'name',f.name,'amount',f.amount,'fund',f.fund,'required',f.required_for_draw,'schedule',f.schedule,'key',fee_key(f.id,cp),
      'paid',(select count(*) from payments y join members m on m.id=y.member_id and m.active=1 where y.fee_type_id=f.id and y.period=fee_key(f.id,cp)),
      'realized',(select coalesce(sum(amount),0) from payments where fee_type_id=f.id and period=fee_key(f.id,cp))::bigint,
      'members',(select count(*) from members where active=1)) order by f.sort,f.id) from fee_types f where f.active),'[]'::jsonb),
  'arrears',(select jsonb_build_object('members',count(distinct a.member_id),'amount',coalesce(sum(a.total),0)) from jsonb_to_recordset(public.iuran_arrears(null,false)) as a(member_id bigint,total bigint)),
  'pending',coalesce((select jsonb_agg(jsonb_build_object('period',d.period,'winner',d.winner_name,'winner_id',d.winner_id,
      'collected',c.coll,'disbursed',c.disb,'amount',c.coll-c.disb) order by d.id desc)
     from draws d cross join lateral (select
        coalesce((select sum(y.amount) from payments y join fee_types f on f.id=y.fee_type_id where y.period=d.period and f.fund='arisan'),0)::bigint coll,
        coalesce((select sum(amount) from transactions where category='Pencairan Arisan' and period=d.period),0)::bigint disb) c
     where d.status='sah' and coalesce((select x.seq from arisan_rounds x where x.period=d.period),0)>=dseq and c.coll-c.disb>0),'[]'::jsonb),
  'monthly',coalesce((select jsonb_agg(to_jsonb(x) order by x.m) from (
      select to_char(date,'YYYY-MM') m,
       coalesce(sum(amount) filter(where type='masuk' and fund='arisan'),0)::bigint masuk_arisan,coalesce(sum(amount) filter(where type='masuk' and fund='kas'),0)::bigint masuk_kas,
       coalesce(sum(amount) filter(where type='keluar'),0)::bigint keluar
      from transactions where date>=(date_trunc('month',now() at time zone 'Asia/Jakarta')-interval '5 months')::date group by 1 order by 1) x),'[]'::jsonb));
 return r;
end $$;

create or replace function public.eligible_members(p text) returns table(id bigint,name text) language sql stable security definer set search_path=public as $$
 select m.id,m.name from members m where m.active=1
 and not exists(select 1 from fee_types f where f.active and f.required_for_draw and not exists(select 1 from payments y where y.member_id=m.id and y.period=public.fee_key(f.id,p) and y.fee_type_id=f.id))
 and not exists(select 1 from draws d where d.winner_id=m.id and (
       (d.status='sah' and d.cycle=cfg('cycle')::int)
    or (d.status in('menunggu','tidak_hadir') and d.period=p)))
 order by m.id $$;

