-- ============================================================
-- PATCH 018 — PUTARAN ARISAN FLEKSIBEL, tidak terikat bulan (FamilyHub v3.16)
--  Masalah: sampai v3.15 arisan dianggap berjalan SEBULAN SEKALI (periode = bulan 'YYYY-MM'). Kenyataannya arisan keluarga
--  digelar mengikuti permintaan anggota: bisa dua kali dalam sebulan, bisa libur dua-tiga bulan. Akibatnya "tunggakan"
--  membengkak untuk bulan di mana memang tidak ada arisan, dan satu bulan hanya muat satu pengocokan.
--  Solusi: satuan arisan kini adalah PUTARAN (sesi), bukan bulan.
--   1) Tabel arisan_rounds: nomor putaran, judul, tanggal (boleh kosong = belum pasti), tempat, anggota yang meminta,
--      catatan, status rencana → aktif → selesai (atau batal), pembuka/penutup & alasan. Paling banyak SATU putaran aktif.
--   2) Iuran punya jadwal: 'putaran' (ditagih per putaran — wajib untuk Iuran Arisan) atau 'bulanan' (mis. Iuran Wajib/kas).
--      Tunggakan iuran 'putaran' = putaran yang sudah selesai tetapi belum dibayar; bulan tanpa arisan TIDAK menunggak.
--   3) Fungsi: create_round, update_round, open_round, close_round, cancel_round, round_state.
--      Setelah putaran ditutup, boleh tidak ada putaran aktif (arisan sedang jeda) sampai ada permintaan berikutnya.
--   4) Pengocokan, pencairan, iuran, tunggakan, laporan, dashboard, portal anggota, Backup/Restore & Reset mengikuti putaran.
--   5) Tabel arisan_periods (patch-015) dimigrasikan ke arisan_rounds lalu dihapus. Kunci periode lama 'YYYY-MM' tetap
--      dipakai sebagai kunci internal putaran lama, sehingga seluruh pembayaran/kocokan/pencairan lama tetap utuh.
--   6) Perbaikan kecil: penghapusan akun (delete_user) kini benar-benar tercatat di jejak audit.
-- Aman dijalankan berulang. Prasyarat: patch-015 (dan patch-016/017 bila sudah ada).
-- ============================================================

-- ---------- 1. Jadwal pada jenis iuran ----------
alter table public.fee_types add column if not exists schedule text not null default 'bulanan';
alter table public.fee_types drop constraint if exists fee_types_schedule_chk;
alter table public.fee_types add constraint fee_types_schedule_chk check(schedule in('bulanan','putaran'));

create or replace function public.trg_fee_schedule() returns trigger language plpgsql set search_path=public as $$
begin if new.fund='arisan' then new.schedule:='putaran'; end if; return new; end $$;      -- dana arisan selalu ditagih per putaran
drop trigger if exists fee_schedule on public.fee_types;
create trigger fee_schedule before insert or update on public.fee_types for each row execute function public.trg_fee_schedule();

do $$ begin
 perform set_config('fh.skip_recalc','1',true);       -- penyesuaian skema bukan perubahan oleh pengguna: tanpa jejak audit
 update public.fee_types set schedule='putaran' where fund='arisan' and schedule<>'putaran';
 perform set_config('fh.skip_recalc','0',true);
end $$;

-- Pembayaran kini boleh memakai kunci putaran ('P001', …) selain bulan ('YYYY-MM')
alter table public.payments drop constraint if exists payments_period_check;
alter table public.payments drop constraint if exists payments_period_chk;
alter table public.payments add constraint payments_period_chk check(period ~ '^(\d{4}-\d{2}|P\d{3,6})$');

-- ---------- 2. Tabel putaran ----------
create table if not exists public.arisan_rounds(
  id bigint generated by default as identity primary key,
  seq int not null unique check(seq>0),                                                   -- nomor putaran (1, 2, 3, …)
  period text not null unique check(char_length(period) between 3 and 12 and period !~ '\s'),   -- kunci internal ('P001'; putaran lama = 'YYYY-MM')
  title text check(title is null or char_length(title) between 1 and 80),
  status text not null default 'rencana' check(status in('rencana','aktif','selesai','batal')),
  held_on date,                                                                           -- tanggal pelaksanaan; kosong = belum pasti
  place text check(place is null or char_length(place)<=120),
  requested_by bigint references public.members(id) on delete set null,                  -- anggota yang meminta arisan digelar
  note text check(note is null or char_length(note)<=500),
  created_at timestamptz not null default now(), created_by text,
  opened_at timestamptz, opened_by text,
  closed_at timestamptz, closed_by text, close_note text,
  check((status in('selesai','batal')) = (closed_at is not null)));
create unique index if not exists arisan_rounds_satu_aktif on public.arisan_rounds((true)) where status='aktif';   -- paling banyak SATU putaran aktif
alter table public.arisan_rounds enable row level security;
drop policy if exists "baca" on public.arisan_rounds;
create policy "baca" on public.arisan_rounds for select to authenticated using (public.is_approved());
revoke all on public.arisan_rounds from anon, authenticated;
grant select on public.arisan_rounds to authenticated;          -- tulis HANYA lewat fungsi (create_round, open_round, …)

-- ---------- 3. Pembantu ----------
-- Putaran aktif (NULL bila arisan sedang jeda). Tidak lagi jatuh ke bulan kalender.
create or replace function public.cur_period() returns text language sql stable set search_path=public as $$
 select period from arisan_rounds where status='aktif' $$;

-- Tanggal acuan putaran: tanggal pelaksanaan, atau (putaran lama) bulan kuncinya, atau tanggal dibuka/dibuat.
create or replace function public.round_ref(r public.arisan_rounds) returns date language sql stable set search_path=public as $$
 select coalesce(r.held_on,
   case when r.period ~ '^\d{4}-(0[1-9]|1[0-2])$' then to_date(r.period||'-01','YYYY-MM-DD') end,
   (r.opened_at at time zone 'Asia/Jakarta')::date,(r.created_at at time zone 'Asia/Jakarta')::date) $$;

-- Bulan acuan untuk iuran bulanan: bulan pelaksanaan putaran (bila bertanggal), selain itu bulan kalender.
create or replace function public.ref_month(p text) returns text language sql stable set search_path=public as $$
 select coalesce((select to_char(held_on,'YYYY-MM') from arisan_rounds where period=p and held_on is not null),calendar_period()) $$;

-- Kunci periode yang berlaku untuk satu jenis iuran pada satu putaran: 'putaran' → kunci putaran, 'bulanan' → bulan acuan.
create or replace function public.fee_key(p_fee smallint,p text) returns text language sql stable set search_path=public as $$
 select case when f.schedule='putaran' then p else ref_month(p) end from fee_types f where f.id=p_fee $$;

-- Nama tampilan putaran untuk keterangan transaksi/log.
create or replace function public.period_label(p text) returns text language sql stable set search_path=public as $$
 select coalesce((select 'Putaran '||seq from arisan_rounds where period=p),p) $$;

create or replace function public.rounds_brief() returns jsonb language sql stable security definer set search_path=public as $$
 select coalesce(jsonb_agg(jsonb_build_object('period',r.period,'seq',r.seq,'title',r.title,'status',r.status,'held_on',r.held_on,'ref',round_ref(r)) order by r.seq desc),'[]'::jsonb) from arisan_rounds r $$;

create or replace function public.round_info(p text) returns jsonb language sql stable security definer set search_path=public as $$
 select (select to_jsonb(r)||jsonb_build_object('requester',(select name from members where id=r.requested_by),'ref',round_ref(r)) from arisan_rounds r where r.period=p) $$;

-- Pembatas pencairan: nomor putaran pertama yang dilacak pencairannya (menggantikan setelan teks 'disburse_from').
create or replace function public._calc_disburse_seq(p_old text) returns text language sql stable security definer set search_path=public as $$
 select coalesce((select min(seq) from arisan_rounds where period>=coalesce(p_old,'') and period ~ '^\d{4}-\d{2}$'),(select coalesce(max(seq),0)+1 from arisan_rounds))::text $$;

-- Pastikan setiap kunci yang dipakai kocokan / iuran arisan / pencairan punya baris putaran (data lama, Restore backup lama, seed).
create or replace function public._ensure_rounds() returns void language plpgsql security definer set search_path=public as $$
begin
 insert into arisan_rounds(seq,period,status,held_on,created_by,opened_at,opened_by,closed_at,closed_by,close_note)
 select coalesce((select max(seq) from arisan_rounds),0)+(row_number() over(order by k.period))::int,k.period,'selesai',k.held,'sistem',now(),'sistem',now(),'sistem','Dibentuk otomatis dari data yang sudah ada'
 from (select u.period,max(u.dt) held from (
        select d.period,(d.at at time zone 'Asia/Jakarta')::date dt from draws d where d.status='sah'
        union all select d.period,null::date from draws d
        union all select y.period,null::date from payments y join fee_types f on f.id=y.fee_type_id where f.schedule='putaran'
        union all select t.period,null::date from transactions t where t.category='Pencairan Arisan' and t.period is not null) u
       where u.period is not null and char_length(u.period) between 3 and 12 and u.period !~ '\s' group by u.period) k
 where not exists(select 1 from arisan_rounds r where r.period=k.period);
end $$;

-- ---------- 4. Migrasi dari arisan_periods (patch-015) ----------
do $$
begin
 if to_regclass('public.arisan_periods') is not null then
  perform set_config('fh.skip_recalc','1',true);
  insert into public.arisan_rounds(seq,period,status,held_on,created_at,created_by,opened_at,opened_by,closed_at,closed_by,close_note)
  select (row_number() over(order by p.period))::int+coalesce((select max(seq) from public.arisan_rounds),0),p.period,p.status,
    (select max((d.at at time zone 'Asia/Jakarta')::date) from public.draws d where d.period=p.period and d.status='sah'),
    p.opened_at,coalesce(p.opened_by,'sistem'),p.opened_at,p.opened_by,p.closed_at,p.closed_by,p.close_note
  from public.arisan_periods p where not exists(select 1 from public.arisan_rounds r where r.period=p.period)
    and not (p.status='aktif' and p.opened_by='sistem'          -- periode aktif bentukan otomatis (bulan kalender) yang masih kosong bukan putaran sungguhan
      and not exists(select 1 from public.draws d where d.period=p.period)
      and not exists(select 1 from public.payments y join public.fee_types f on f.id=y.fee_type_id where y.period=p.period and f.fund='arisan')
      and not exists(select 1 from public.transactions t where t.period=p.period and t.category='Pencairan Arisan'));
  drop table public.arisan_periods;
  perform set_config('fh.skip_recalc','0',true);
 end if;
end $$;
select public._ensure_rounds();       -- instalasi sangat lama / seed: bentuk putaran dari kocokan & iuran yang ada
insert into public.settings(k,v) select 'disburse_from_seq',public._calc_disburse_seq(public.cfg('disburse_from')) on conflict(k) do nothing;

drop function if exists public.period_state();
drop function if exists public.set_active_period(text,text,boolean);
drop function if exists public._ensure_periods();

